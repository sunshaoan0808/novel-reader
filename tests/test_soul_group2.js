const fs = require("fs"), vm = require("vm");
const store = {};
const localStorage = {getItem: k => store[k] || null, setItem: (k,v) => store[k]=String(v), removeItem: k => delete store[k]};
const ctx = {console, localStorage};
ctx.window = ctx; ctx.globalThis = ctx;
vm.createContext(ctx);
vm.runInContext(fs.readFileSync("www/rp/soul_group.js", "utf8"), ctx, {filename: "rp/soul_group.js"});
const G = ctx.RP_SOUL_GROUP;
let pass = 0, fail = 0;
const t = (n, c) => { c ? pass++ : (fail++, console.log("FAIL:", n)); };
const CH = "test_chat";

/* 16 */ G.setOrder(CH, "random"); t("16. 发言顺序", G.getOrder(CH) === "random");
/* 17 */ G.setMaxTurns(CH, 50); t("17. 轮次上限", G.getMaxTurns(CH) === 50 && G.checkTurnLimit(CH, 50) && !G.checkTurnLimit(CH, 49));
/* 18 */ G.exitSoul(CH, "黛玉"); t("18. 退场", G.isExited(CH, "黛玉") && G.activeMembers(CH, ["黛玉", "宝玉"]).length === 1);
G.enterSoul(CH, "黛玉"); t("18. 入场", !G.isExited(CH, "黛玉"));
/* 19 */ G.setPaused(CH, true); t("19. 暂停", G.isPaused(CH)); G.setPaused(CH, false);
/* 20 */ G.branch(CH, [1,2,3], "分支A"); t("20. 分支", G.getBranches(CH).length === 1);
/* 21 */ var pm = G.markPrivate({content: "悄悄话"}); t("21. 私聊", G.isPrivate(pm) && G.filterPublic([pm, {content: "公开"}]).length === 1);
/* 22 */ G.startVote(CH, "去哪", ["A", "B"]); G.castVote(CH, "黛玉", "A"); G.castVote(CH, "宝玉", "B"); G.castVote(CH, "宝钗", "A");
var tally = G.tallyVote(CH); t("22. 投票", tally.winner === "A" && tally.total === 3);
/* 23 */ G.setDebate(CH, "黛玉", "宝玉", 2);
t("23. 辩论", G.debateNext(CH) === "黛玉" && G.debateNext(CH) === "宝玉" && G.debateNext(CH) === "黛玉");
G.endDebate(CH);
/* 24 */ G.setNarrator(CH, true); t("24. 旁白", G.isNarrator(CH));
/* 25 */ t("25. 接龙", G.chainNext(CH, ["A","B","C"], "B") === "C" && G.chainNext(CH, ["A","B"], "B") === "A");
/* 26 */ G.mute(CH, "黛玉"); t("26. 禁言", G.isMuted(CH, "黛玉")); G.unmute(CH, "黛玉"); t("26. 解禁", !G.isMuted(CH, "黛玉"));
/* 27 */ G.setSpeed(CH, "fast"); t("27. 变速", G.getSpeed(CH) === "fast" && G.speedMaxTokens(CH) === 200);
/* 28 */ G.setMood(CH, "欢乐"); t("28. 情绪", G.getMood(CH) === "欢乐");
/* 29 */ G.injectEvent(CH, "天降陨石"); t("29. 事件注入", G.peekEvents(CH).length === 1 && G.popEvent(CH).text === "天降陨石");
/* 30 */ G.setShareMem(CH, false); t("30. 记忆共享", !G.isShareMem(CH)); G.setShareMem(CH, true);
/* 31 */ G.checkpoint(CH, [1,2]); t("31. 存档点", true);
/* 32 */ t("32. 回放", G.replayRange([1,2,3,4], 1, 3).length === 2);
/* 33 */ G.setWordLimit(CH, 10); t("33. 字数限制", G.trimToLimit(CH, "1234567890123").length === 11);
/* 34 */ t("34. 敏感词", G.filterBad(CH, "你傻逼").indexOf("傻逼") < 0);
/* 35 */ G.setAutoExit(CH, 5);
var quiet = G.checkAutoExit(CH, ["黛玉", "宝玉"], [{speaker: "宝玉"}], 5);
t("35. 自动退场", quiet.indexOf("黛玉") >= 0 && quiet.indexOf("宝玉") < 0);

console.log("\nPASS: " + pass + " FAIL: " + fail);
process.exit(fail ? 1 : 0);
